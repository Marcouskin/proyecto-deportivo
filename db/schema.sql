-- Esquema relacional derivado del diagrama E-R del proyecto.
-- PostgreSQL 13+. ATENCIÓN: elimina y vuelve a crear todas las tablas.

DROP TABLE IF EXISTS historial_cambio, reporte, verificacion, notificacion,
  usuario_disciplina, oportunidad_guardada, usuario_rol, rol, usuario,
  fuente, requisito, horario, oportunidad_disciplina, oportunidad_unidad,
  convocatoria, beca, actividad, oportunidad, contacto, organizador,
  sede_disciplina, disciplina, sede, unidad_academica CASCADE;

-- ---------- Catálogos ----------

CREATE TABLE unidad_academica (
  id_unidad        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(200) NOT NULL,
  siglas           VARCHAR(30)  NOT NULL UNIQUE,
  nivel_educativo  VARCHAR(40)  NOT NULL,
  zona             VARCHAR(60)  NOT NULL
);

-- UNIDAD ACADÉMICA 1 — tiene — N SEDE
CREATE TABLE sede (
  id_sede         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_unidad       INT NOT NULL REFERENCES unidad_academica(id_unidad),
  nombre          VARCHAR(200) NOT NULL,
  direccion       VARCHAR(300),
  latitud         NUMERIC(9,6),
  longitud        NUMERIC(9,6),
  horario_acceso  VARCHAR(120),
  activo          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE disciplina (
  id_disciplina  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(100) NOT NULL UNIQUE,
  descripcion    TEXT,
  activo         BOOLEAN NOT NULL DEFAULT TRUE
);

-- SEDE N — ofrece — M DISCIPLINA
CREATE TABLE sede_disciplina (
  id_sede        INT NOT NULL REFERENCES sede(id_sede) ON DELETE CASCADE,
  id_disciplina  INT NOT NULL REFERENCES disciplina(id_disciplina) ON DELETE CASCADE,
  PRIMARY KEY (id_sede, id_disciplina)
);

CREATE TABLE organizador (
  id_organizador    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre            VARCHAR(200) NOT NULL,
  tipo_organizador  VARCHAR(60)  NOT NULL
);

-- ORGANIZADOR 1 — se contacta — N CONTACTO
CREATE TABLE contacto (
  id_contacto     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizador  INT NOT NULL REFERENCES organizador(id_organizador) ON DELETE CASCADE,
  tipo_contacto   VARCHAR(30)  NOT NULL CHECK (tipo_contacto IN ('correo','telefono','web','red_social','presencial')),
  valor           VARCHAR(300) NOT NULL
);

-- ---------- Oportunidad y su especialización ----------

-- ORGANIZADOR 1 — publica — N OPORTUNIDAD
CREATE TABLE oportunidad (
  id_oportunidad       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_organizador       INT NOT NULL REFERENCES organizador(id_organizador),
  titulo               VARCHAR(200) NOT NULL,
  descripcion          TEXT NOT NULL,
  tipo                 VARCHAR(20)  NOT NULL CHECK (tipo IN ('actividad','beca','convocatoria')),
  estado_vigencia      VARCHAR(20)  NOT NULL DEFAULT 'vigente' CHECK (estado_vigencia IN ('vigente','proxima','cerrada')),
  url_oficial          VARCHAR(500),
  destacada            BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_publicacion    TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
  activo               BOOLEAN NOT NULL DEFAULT TRUE
);

-- ES UN (disjunta, total): cada oportunidad tiene exactamente una fila en la
-- subtabla que indica "tipo". La aplicación la inserta en la misma transacción.
CREATE TABLE actividad (
  id_oportunidad   INT PRIMARY KEY REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  nivel_deportivo  VARCHAR(60),
  cupo             INT CHECK (cupo IS NULL OR cupo >= 0),
  costo            NUMERIC(10,2) CHECK (costo IS NULL OR costo >= 0)
);

CREATE TABLE beca (
  id_oportunidad  INT PRIMARY KEY REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  monto           NUMERIC(10,2) CHECK (monto IS NULL OR monto >= 0),
  beneficios      TEXT,
  periodo         VARCHAR(80)
);

CREATE TABLE convocatoria (
  id_oportunidad   INT PRIMARY KEY REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  evento           VARCHAR(200),
  fecha_apertura   DATE,
  fecha_cierre     DATE,
  url_inscripcion  VARCHAR(500),
  CHECK (fecha_cierre IS NULL OR fecha_apertura IS NULL OR fecha_cierre >= fecha_apertura)
);

-- OPORTUNIDAD N — aplica en — M UNIDAD ACADÉMICA
CREATE TABLE oportunidad_unidad (
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  id_unidad       INT NOT NULL REFERENCES unidad_academica(id_unidad) ON DELETE CASCADE,
  PRIMARY KEY (id_oportunidad, id_unidad)
);

-- OPORTUNIDAD N — se clasifica — M DISCIPLINA
CREATE TABLE oportunidad_disciplina (
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  id_disciplina   INT NOT NULL REFERENCES disciplina(id_disciplina) ON DELETE CASCADE,
  PRIMARY KEY (id_oportunidad, id_disciplina)
);

-- OPORTUNIDAD 1 — establece — N HORARIO;  SEDE 1 — alberga — N HORARIO
CREATE TABLE horario (
  id_horario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  id_sede         INT NOT NULL REFERENCES sede(id_sede),
  dia_semana      SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7), -- 1 = lunes
  hora_inicio     TIME NOT NULL,
  hora_fin        TIME NOT NULL,
  CHECK (hora_fin > hora_inicio)
);

-- OPORTUNIDAD 1 — solicita — N REQUISITO
CREATE TABLE requisito (
  id_requisito    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  descripcion     VARCHAR(400) NOT NULL,
  obligatorio     BOOLEAN NOT NULL DEFAULT TRUE
);

-- OPORTUNIDAD 1 — documenta — N FUENTE
CREATE TABLE fuente (
  id_fuente       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  nombre          VARCHAR(200) NOT NULL,
  url             VARCHAR(500),
  tipo_fuente     VARCHAR(40) NOT NULL DEFAULT 'portal',
  fecha_consulta  DATE NOT NULL DEFAULT CURRENT_DATE
);

-- ---------- Usuarios ----------

-- USUARIO N — estudia en — 1 UNIDAD ACADÉMICA
CREATE TABLE usuario (
  id_usuario       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_unidad        INT REFERENCES unidad_academica(id_unidad),
  nombre           VARCHAR(150) NOT NULL,
  correo           VARCHAR(200) NOT NULL UNIQUE,
  contrasena_hash  VARCHAR(100) NOT NULL,
  fecha_registro   TIMESTAMPTZ NOT NULL DEFAULT now(),
  activo           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE rol (
  id_rol       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(40) NOT NULL UNIQUE,
  descripcion  VARCHAR(200)
);

-- USUARIO N — tiene rol — M ROL (atributo: fecha_asignación)
CREATE TABLE usuario_rol (
  id_usuario        INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_rol            INT NOT NULL REFERENCES rol(id_rol) ON DELETE CASCADE,
  fecha_asignacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_usuario, id_rol)
);

-- USUARIO N — guarda — M OPORTUNIDAD (atributo: fecha_guardado)
CREATE TABLE oportunidad_guardada (
  id_usuario      INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  fecha_guardado  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_usuario, id_oportunidad)
);

-- USUARIO N — prefiere — M DISCIPLINA
CREATE TABLE usuario_disciplina (
  id_usuario     INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_disciplina  INT NOT NULL REFERENCES disciplina(id_disciplina) ON DELETE CASCADE,
  PRIMARY KEY (id_usuario, id_disciplina)
);

-- USUARIO 1 — recibe — N NOTIFICACIÓN;  OPORTUNIDAD 1 — origina — N NOTIFICACIÓN
CREATE TABLE notificacion (
  id_notificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario       INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_oportunidad   INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  mensaje          VARCHAR(400) NOT NULL,
  tipo             VARCHAR(30)  NOT NULL DEFAULT 'actualizacion',
  fecha_envio      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  leida            BOOLEAN NOT NULL DEFAULT FALSE
);

-- USUARIO 1 — verifica — N VERIFICACIÓN;  OPORTUNIDAD 1 — es verificada — N VERIFICACIÓN
CREATE TABLE verificacion (
  id_verificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario       INT NOT NULL REFERENCES usuario(id_usuario),
  id_oportunidad   INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  fecha            TIMESTAMPTZ NOT NULL DEFAULT now(),
  resultado        VARCHAR(20) NOT NULL CHECK (resultado IN ('vigente','desactualizada','no_encontrada')),
  observaciones    TEXT
);

-- USUARIO 1 — reporta — N REPORTE;  OPORTUNIDAD 1 — es reportada — N REPORTE
CREATE TABLE reporte (
  id_reporte      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INT NOT NULL REFERENCES usuario(id_usuario),
  id_oportunidad  INT NOT NULL REFERENCES oportunidad(id_oportunidad) ON DELETE CASCADE,
  motivo          VARCHAR(40) NOT NULL CHECK (motivo IN ('informacion_incorrecta','desactualizada','enlace_roto','otro')),
  descripcion     TEXT,
  fecha           TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado          VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','atendido','descartado'))
);

-- USUARIO 1 — registra — N HISTORIAL CAMBIO
CREATE TABLE historial_cambio (
  id_cambio       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INT NOT NULL REFERENCES usuario(id_usuario),
  tabla_afectada  VARCHAR(60) NOT NULL,
  id_registro     INT NOT NULL,
  accion          VARCHAR(20) NOT NULL CHECK (accion IN ('crear','actualizar','eliminar','verificar')),
  detalle         TEXT,
  fecha           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_oportunidad_tipo     ON oportunidad (tipo) WHERE activo;
CREATE INDEX idx_horario_oportunidad  ON horario (id_oportunidad, dia_semana);
CREATE INDEX idx_reporte_estado       ON reporte (estado);
CREATE INDEX idx_notificacion_usuario ON notificacion (id_usuario, leida);
